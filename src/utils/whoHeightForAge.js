/**
 * Length/height-for-age Z-score using the WHO LMS method.
 * Returns null when inputs are missing or out of range.
 */
export function getLengthForAgeZScore(heightCm, ageMonths, sex) {
  const h = parseFloat(heightCm)
  const a = parseInt(ageMonths, 10)
  if (!h || h <= 0 || isNaN(a) || !sex) return null
  if (a < 0 || a > 59) return null
  const table = LFA_LMS[sex === 'Male' ? 'boys' : 'girls']
  const [L, M, S] = table[a]
  return ((Math.pow(h / M, L) - 1) / (L * S))
}

/** DHS/WHO height-for-age (stunting) classification */
export function classifyHeightForAge(zScore) {
  if (zScore === null || zScore === undefined || isNaN(zScore)) return ''
  if (zScore < -3.0) return 'Severely Stunted'
  if (zScore < -2.0) return 'Moderately Stunted'
  if (zScore > 2.0) return 'Tall'
  return 'Normal'
}
