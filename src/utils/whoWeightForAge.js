/**
 * Weight-for-age Z-score using the WHO LMS method.
 * Returns null when inputs are missing or out of range.
 */
export function getWeightForAgeZScore(weightKg, ageMonths, sex) {
  const w = parseFloat(weightKg)
  const a = parseInt(ageMonths, 10)
  if (!w || w <= 0 || isNaN(a) || !sex) return null
  if (a < 0 || a > 59) return null
  const table = WFA_LMS[sex === 'Male' ? 'boys' : 'girls']
  const [L, M, S] = table[a]
  return ((Math.pow(w / M, L) - 1) / (L * S))
}

/** DHS/WHO weight-for-age classification */
export function classifyWeightForAge(zScore) {
  if (zScore === null || zScore === undefined || isNaN(zScore)) return ''
  if (zScore < -3.0) return 'Severely Underweight'
  if (zScore < -2.0) return 'Moderately Underweight'
  if (zScore > 2.0) return 'Overweight'
  return 'Normal'
}
